// Calculator 1: Digit Frequency (Primary Draws)
export function getDigitStats(history = []) {
  // Safe extraction of flat draws for frequency calculation
  const counts = Array(10).fill(0);
  let totalTwoDigits = 0;

  history.forEach(draw => {
    // If nested object format
    const twoDigits = draw.twoDigitBack;
    if (twoDigits && twoDigits.length === 2) {
      counts[parseInt(twoDigits[0])]++;
      counts[parseInt(twoDigits[1])]++;
      totalTwoDigits += 2;
    }
  });

  return counts.map((count, index) => ({
    digit: index,
    count,
    percentage: parseFloat(((count / (totalTwoDigits || 1)) * 100).toFixed(1))
  }));
}

// Calculator 2: Dynamic Probability Model using Upgraded Multi-Agent AI Hybrid Ensemble Model v2
export function getPredictionStats(history = []) {
  if (history.length === 0) return [];

  // Fallback if data is too small to compute advanced matrices
  if (history.length < 5) {
    return Array(10).fill(0).map((_, i) => ({
      digit: i,
      probability: 10,
      lastSeen: 1
    }));
  }

  const size = Math.min(history.length, 25);

  // --- LAYER 1: EXPONENTIAL RECENCY MOMENTUM ---
  const recencyCounts = Array(10).fill(0);
  let totalWeights = 0;
  for (let i = 0; i < size; i++) {
    const draw = history[i];
    const weight = Math.pow(0.86, i);
    const d1 = draw.twoDigitBack;
    if (d1 && d1.length === 2) {
      recencyCounts[parseInt(d1[0])] += weight;
      recencyCounts[parseInt(d1[1])] += weight;
      totalWeights += (weight * 2);
    }
  }
  const recencyScores = recencyCounts.map(count => count / (totalWeights || 1));

  // --- LAYER 2: DIGIT CO-OCCURRENCE CORRELATION ---
  const coOccur = Array(10).fill(0).map(() => Array(10).fill(0));
  history.forEach(draw => {
    const d = draw.twoDigitBack;
    if (d && d.length === 2) {
      const u = parseInt(d[0]);
      const v = parseInt(d[1]);
      coOccur[u][v]++;
      coOccur[v][u]++;
    }
  });
  const coOccurScores = Array(10).fill(0);
  for (let u = 0; u < 10; u++) {
    let partnerSum = 0;
    for (let v = 0; v < 10; v++) {
      partnerSum += coOccur[u][v];
    }
    coOccurScores[u] = partnerSum / (history.length || 1);
  }
  const sumCoOccur = coOccurScores.reduce((a, b) => a + b, 0);
  const normalizedCoOccur = coOccurScores.map(val => val / (sumCoOccur || 1));

  // --- LAYER 3: REGRESSION-TO-THE-MEAN OVERDUE ABSENCE ---
  const lastSeen = Array(10).fill(99);
  for (let d = 0; d < 10; d++) {
    for (let i = 0; i < history.length; i++) {
      const d1 = history[i].twoDigitBack;
      if (d1 && (parseInt(d1[0]) === d || parseInt(d1[1]) === d)) {
        lastSeen[d] = i;
        break;
      }
    }
  }
  const overdueScores = lastSeen.map(gap => Math.min(gap, 15) / 15);

  // --- LAYER 4: MARKOV CHAIN STATE-TRANSITION PROBABILITY ---
  const transitionMatrix = Array(10).fill(0).map(() => Array(10).fill(0));
  for (let i = 0; i < history.length - 1; i++) {
    const currentDraw = history[i].twoDigitBack;
    const nextDraw = history[i + 1].twoDigitBack;
    if (currentDraw && currentDraw.length === 2 && nextDraw && nextDraw.length === 2) {
      const cur1 = parseInt(currentDraw[0]);
      const cur2 = parseInt(currentDraw[1]);
      const nxt1 = parseInt(nextDraw[0]);
      const nxt2 = parseInt(nextDraw[1]);
      
      transitionMatrix[nxt1][cur1]++;
      transitionMatrix[nxt1][cur2]++;
      transitionMatrix[nxt2][cur1]++;
      transitionMatrix[nxt2][cur2]++;
    }
  }
  
  const markovScores = Array(10).fill(0);
  const latestDraw = history[0].twoDigitBack;
  if (latestDraw && latestDraw.length === 2) {
    const lat1 = parseInt(latestDraw[0]);
    const lat2 = parseInt(latestDraw[1]);
    for (let d = 0; d < 10; d++) {
      const transProb = (transitionMatrix[lat1][d] + transitionMatrix[lat2][d]) / 2;
      markovScores[d] = transProb;
    }
  }
  const sumMarkov = markovScores.reduce((a, b) => a + b, 0);
  const normalizedMarkov = markovScores.map(val => val / (sumMarkov || 1));

  // --- LAYER 5: POSITIONAL AUTOCORRELATION (TENS vs ONES PLACE) ---
  const tensCounts = Array(10).fill(0);
  const onesCounts = Array(10).fill(0);
  const posLimit = Math.min(history.length, 15);
  for (let i = 0; i < posLimit; i++) {
    const d = history[i].twoDigitBack;
    if (d && d.length === 2) {
      const w = Math.pow(0.90, i);
      tensCounts[parseInt(d[0])] += w;
      onesCounts[parseInt(d[1])] += w;
    }
  }
  const positionalScores = Array(10).fill(0);
  for (let d = 0; d < 10; d++) {
    positionalScores[d] = (tensCounts[d] + onesCounts[d]) / 2;
  }
  const sumPos = positionalScores.reduce((a, b) => a + b, 0);
  const normalizedPositional = positionalScores.map(val => val / (sumPos || 1));

  // --- LAYER 6: ARITHMETIC DIGIT-SUM DISTRIBUTION ---
  const sumCounts = Array(19).fill(0);
  let sumWeights = 0;
  for (let i = 0; i < posLimit; i++) {
    const d = history[i].twoDigitBack;
    if (d && d.length === 2) {
      const w = Math.pow(0.90, i);
      const digitSum = parseInt(d[0]) + parseInt(d[1]);
      sumCounts[digitSum] += w;
      sumWeights += w;
    }
  }
  const sumProbabilities = sumCounts.map(count => count / (sumWeights || 1));
  const arithmeticScores = Array(10).fill(0);
  for (let d = 0; d < 10; d++) {
    let scoreSum = 0;
    for (let other = 0; other < 10; other++) {
      scoreSum += sumProbabilities[d + other];
    }
    arithmeticScores[d] = scoreSum / 10;
  }
  const sumArith = arithmeticScores.reduce((a, b) => a + b, 0);
  const normalizedArithmetic = arithmeticScores.map(val => val / (sumArith || 1));

  // --- SELF-TUNING WEIGHT OPTIMIZATION ENGINE (LOCAL BACKTEST GRID SEARCH v2) ---
  const configurations = [
    { name: "Agent A (Recency Heavy)", wRec: 0.40, wCo: 0.10, wOvd: 0.10, wMrk: 0.15, wPos: 0.15, wAr: 0.10 },
    { name: "Agent B (Markov Heavy)", wRec: 0.20, wCo: 0.10, wOvd: 0.10, wMrk: 0.40, wPos: 0.10, wAr: 0.10 },
    { name: "Agent C (Mean Reversion Heavy)", wRec: 0.15, wCo: 0.10, wOvd: 0.45, wMrk: 0.10, wPos: 0.10, wAr: 0.10 },
    { name: "Agent D (Positional Heavy)", wRec: 0.20, wCo: 0.10, wOvd: 0.10, wMrk: 0.10, wPos: 0.40, wAr: 0.10 },
    { name: "Agent E (Arithmetic Sum Heavy)", wRec: 0.15, wCo: 0.10, wOvd: 0.10, wMrk: 0.10, wPos: 0.15, wAr: 0.40 }
  ];

  const getCombinedScores = (c) => {
    const scores = [];
    for (let d = 0; d < 10; d++) {
      scores.push(
        (recencyScores[d] * c.wRec) + 
        (normalizedCoOccur[d] * c.wCo) + 
        (overdueScores[d] * c.wOvd) + 
        (normalizedMarkov[d] * c.wMrk) +
        (normalizedPositional[d] * c.wPos) +
        (normalizedArithmetic[d] * c.wAr)
      );
    }
    return scores;
  };

  let bestConfig = configurations[0];
  let maxHits = -1;

  // Backtest config agents over the last 8 draws to choose the best weights
  configurations.forEach(config => {
    let hits = 0;
    const backtestLimit = Math.min(history.length - 2, 8);
    for (let b = 1; b <= backtestLimit; b++) {
      const precedingData = history.slice(b + 1);
      if (precedingData.length < 3) continue;

      const bSize = Math.min(precedingData.length, 25);
      const bRecCounts = Array(10).fill(0);
      let bTotalW = 0;
      for (let i = 0; i < bSize; i++) {
        const draw = precedingData[i];
        const w = Math.pow(0.86, i);
        const d1 = draw.twoDigitBack;
        if (d1 && d1.length === 2) {
          bRecCounts[parseInt(d1[0])] += w;
          bRecCounts[parseInt(d1[1])] += w;
          bTotalW += (w * 2);
        }
      }
      const bRecScores = bRecCounts.map(count => count / (bTotalW || 1));
      
      const bOvdGaps = Array(10).fill(99);
      for (let d = 0; d < 10; d++) {
        for (let i = 0; i < precedingData.length; i++) {
          const d1 = precedingData[i].twoDigitBack;
          if (d1 && (parseInt(d1[0]) === d || parseInt(d1[1]) === d)) {
            bOvdGaps[d] = i;
            break;
          }
        }
      }
      const bOvdScores = bOvdGaps.map(gap => Math.min(gap, 15) / 15);

      const combined = [];
      for (let d = 0; d < 10; d++) {
        const val = (bRecScores[d] * config.wRec) + (bOvdScores[d] * config.wOvd);
        combined.push({ digit: d, score: val });
      }
      combined.sort((x, y) => y.score - x.score);
      const top3 = combined.slice(0, 3).map(x => x.digit);

      const actual = history[b].twoDigitBack;
      if (actual && actual.length === 2) {
        const actD1 = parseInt(actual[0]);
        const actD2 = parseInt(actual[1]);
        if (top3.includes(actD1)) hits++;
        if (top3.includes(actD2) && actD1 !== actD2) hits++;
      }
    }

    if (hits > maxHits) {
      maxHits = hits;
      bestConfig = config;
    }
  });

  // Apply best-performing configuration
  const optimizedScores = getCombinedScores(bestConfig);
  const totalScoreSum = optimizedScores.reduce((sum, score) => sum + score, 0);

  const predictionList = [];
  for (let d = 0; d < 10; d++) {
    predictionList.push({
      digit: d,
      probability: Math.round((optimizedScores[d] / (totalScoreSum || 1)) * 100),
      lastSeen: lastSeen[d]
    });
  }

  return predictionList.sort((a, b) => b.probability - a.probability);
}

// Calculator 3: Odd vs Even
export function getOddEvenRatio(history = []) {
  let odd = 0;
  let even = 0;
  
  history.forEach(draw => {
    if (draw.twoDigitBack) {
      const lastDigit = parseInt(draw.twoDigitBack.slice(-1));
      if (lastDigit % 2 === 0) even++;
      else odd++;
    }
  });

  const total = odd + even;
  return {
    odd: Math.round((odd / (total || 1)) * 100),
    even: Math.round((even / (total || 1)) * 100)
  };
}

// Calculator 4: High vs Low
export function getHighLowRatio(history = []) {
  let high = 0;
  let low = 0;

  history.forEach(draw => {
    if (draw.twoDigitBack && draw.twoDigitBack.length === 2) {
      const d1 = parseInt(draw.twoDigitBack[0]);
      const d2 = parseInt(draw.twoDigitBack[1]);
      [d1, d2].forEach(digit => {
        if (digit >= 5) high++;
        else low++;
      });
    }
  });

  const total = high + low;
  return {
    high: Math.round((high / (total || 1)) * 100),
    low: Math.round((low / (total || 1)) * 100)
  };
}

// Backtesting function: Predicts digit probability based on past data (history.slice(index + 1))
// and checks if the actual result (draw at index) matches the top 3 predicted digits.
export function backtestDraw(history = [], index = 0) {
  if (index >= history.length - 1) return { accuracy: 0, matched: [] };
  
  const pastData = history.slice(index + 1);
  const predictions = getPredictionStats(pastData);
  
  // Top 3 predicted digits
  const topDigits = predictions.slice(0, 3).map(p => p.digit);
  
  // Actual 2-digit back
  const actual = history[index].twoDigitBack;
  if (!actual || actual.length !== 2) return { accuracy: 0, matched: [] };
  
  const actD1 = parseInt(actual[0]);
  const actD2 = parseInt(actual[1]);
  
  const matched = [];
  if (topDigits.includes(actD1)) matched.push(actD1);
  if (topDigits.includes(actD2) && actD1 !== actD2) matched.push(actD2);
  
  let accuracy = 0;
  if (matched.length === 2) accuracy = 100;
  else if (matched.length === 1) accuracy = 50;
  
  return {
    accuracy,
    matched,
    topDigits
  };
}

// Global backtest accuracy: Average of the last 10 draws (excluding the oldest since we need past data)
export function getGlobalAccuracy(history = []) {
  if (history.length <= 1) return 0;
  
  const limit = Math.min(history.length - 1, 10);
  let totalAccuracy = 0;
  let count = 0;
  
  for (let i = 0; i < limit; i++) {
    const res = backtestDraw(history, i);
    totalAccuracy += res.accuracy;
    count++;
  }
  
  return count > 0 ? Math.round(totalAccuracy / count) : 0;
}
